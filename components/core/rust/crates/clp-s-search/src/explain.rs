impl fmt::Display for ArchiveSearchPlan {
    /// Writes the EXPLAIN text of the plan: the leaves, the templates, every candidate table with
    /// its filter and bindings, the projection and the filter dictionaries.
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        let num_tables = self.archive_tables().index().tables().tables().len();
        let num_match_all = self
            .tables()
            .iter()
            .filter(|table| matches!(table.filter, TableFilterPlan::MatchAll))
            .count();
        writeln!(
            formatter,
            "plan: {} of {num_tables} tables are candidates ({num_match_all} match-all), {} \
             template(s)",
            self.tables().len(),
            self.templates().len()
        )?;
        writeln!(formatter, "leaves:")?;
        for (index, leaf) in (0_u32..).zip(self.query().leaves()) {
            writeln!(formatter, "  L{index}: {}", leaf_text(leaf))?;
        }
        writeln!(formatter, "templates:")?;
        for template in self.templates() {
            writeln!(
                formatter,
                "  T{}: {}",
                template.index(),
                tree_text(template.root())
            )?;
        }
        writeln!(formatter, "tables:")?;
        for table in self.tables() {
            write!(
                formatter,
                "  #{} ({} rows): ",
                table.table.get(),
                table.num_rows
            )?;
            match &table.filter {
                TableFilterPlan::MatchAll => writeln!(formatter, "match-all")?,
                TableFilterPlan::Residual(residual) => {
                    writeln!(formatter, "T{}", residual.template().index())?;
                    for binding in residual.bindings() {
                        write!(formatter, "    L{}:", binding.leaf.get())?;
                        for column in &binding.columns {
                            write!(
                                formatter,
                                " c{} (node {}) {}",
                                column.column.get(),
                                column.node_id.get(),
                                test_text(&column.test)
                            )?;
                        }
                        if binding.is_false_without_columns {
                            write!(formatter, " +false")?;
                        }
                        writeln!(formatter)?;
                    }
                }
            }
        }
        match self.projection() {
            ResolvedProjection::Full => writeln!(formatter, "projection: full")?,
            ResolvedProjection::Nodes(nodes) => {
                let nodes: Vec<String> = nodes.iter().map(|node| node.get().to_string()).collect();
                writeln!(formatter, "projection: nodes [{}]", nodes.join(", "))?;
            }
        }
        let needs = self.filter_dictionary_needs();
        let mut dictionaries = Vec::new();
        if needs.is_variable_needed {
            dictionaries.push("variable");
        }
        if needs.is_logtype_needed {
            dictionaries.push("logtype");
        }
        if needs.is_array_needed {
            dictionaries.push("array");
        }
        write!(
            formatter,
            "filter dictionaries: {}",
            if dictionaries.is_empty() {
                "none".to_owned()
            } else {
                dictionaries.join(", ")
            }
        )
    }
}

/// # Returns
///
/// The KQL text of a column pattern.
pub fn column_text(pattern: &ColumnPattern) -> String {
    let mut text = String::new();
    match pattern.namespace {
        Namespace::AutoGenerated => text.push('@'),
        Namespace::RangeIndex => text.push('$'),
        Namespace::Reserved(sigil) => text.push(char::from(sigil)),
        _ => {}
    }
    for (index, token) in pattern.tokens.iter().enumerate() {
        if 0 != index {
            text.push('.');
        }
        match token {
            PathToken::AnyDepth => text.push('*'),
            PathToken::Key(key) => {
                for character in String::from_utf8_lossy(key).chars() {
                    if matches!(character, '.' | '*' | '\\') {
                        text.push('\\');
                    }
                    text.push(character);
                }
            }
        }
    }
    text
}

/// # Returns
///
/// The text of one leaf.
fn leaf_text(leaf: &Leaf) -> String {
    let column = match &leaf.column {
        ColumnRef::Path(pattern) | ColumnRef::RangeIndexField(pattern) => column_text(pattern),
        ColumnRef::AnyLeaf => "*".to_owned(),
        ColumnRef::AuthoritativeTimestamp => "<timestamp>".to_owned(),
    };
    match &leaf.test {
        PredicateTest::Exists => format!("{column}: *"),
        PredicateTest::Compare {
            operator,
            value,
            is_case_sensitive,
        } => {
            let operator = match operator {
                CompareOperator::Equal => ":",
                CompareOperator::Less => " <",
                CompareOperator::LessOrEqual => " <=",
                CompareOperator::Greater => " >",
                CompareOperator::GreaterOrEqual => " >=",
            };
            format!(
                "{column}{operator} {}{}",
                value_text(value),
                case_suffix(*is_case_sensitive)
            )
        }
        PredicateTest::InSet {
            values,
            is_case_sensitive,
        } => {
            let values: Vec<String> = values.iter().map(value_text).collect();
            format!(
                "{column}: ({}){}",
                values.join(" "),
                case_suffix(*is_case_sensitive)
            )
        }
        test => format!("{column}: {test:?}"),
    }
}

/// # Returns
///
/// The marker of case-insensitive tests.
const fn case_suffix(is_case_sensitive: bool) -> &'static str {
    if is_case_sensitive {
        ""
    } else {
        " (ignore case)"
    }
}

/// # Returns
///
/// The text of a literal.
fn value_text(value: &QueryValue) -> String {
    match value {
        QueryValue::Integer { text, .. } | QueryValue::Float { text, .. } => text.to_string(),
        QueryValue::Boolean(value) => value.to_string(),
        QueryValue::Null => "null".to_owned(),
        QueryValue::Text(pattern) => {
            format!(
                "\"{}\"",
                String::from_utf8_lossy(&wildcard::render(pattern))
            )
        }
        QueryValue::Timestamp { epoch_ns } => format!("timestamp({epoch_ns} ns)"),
        _ => format!("{value:?}"),
    }
}

/// # Returns
///
/// The text of a residual tree.
fn tree_text(root: &NormalExpr) -> String {
    crate::tree::fold(root, |node| match node {
        crate::tree::FoldNode::Constant(value) => value.to_string(),
        crate::tree::FoldNode::Leaf { leaf, is_negated } => occurrence_text(leaf, is_negated),
        crate::tree::FoldNode::And(children) => format!("({})", children.join(" AND ")),
        crate::tree::FoldNode::Or(children) => format!("({})", children.join(" OR ")),
    })
}

/// # Returns
///
/// The text of one leaf occurrence.
fn occurrence_text(leaf: LeafId, is_negated: bool) -> String {
    if is_negated {
        format!("NOT L{}", leaf.get())
    } else {
        format!("L{}", leaf.get())
    }
}

/// # Returns
///
/// The text of a column test.
fn test_text(column_test: &ColumnTest) -> String {
    match column_test {
        ColumnTest::Value => "value".to_owned(),
        ColumnTest::VariableIds(ids) => format!("ids {ids}"),
        ColumnTest::EncodedText(members) => {
            let mut text = String::from("text [");
            for (index, member) in members.iter().enumerate() {
                if 0 != index {
                    text.push_str(", ");
                }
                let _ = write!(
                    text,
                    "\"{}\" ",
                    String::from_utf8_lossy(&wildcard::render(&member.pattern))
                );
                match &member.prefilter {
                    EncodedTextMatch::Never => text.push_str("never"),
                    EncodedTextMatch::DecodeAll => text.push_str("decode-all"),
                    EncodedTextMatch::Subqueries(subqueries) => {
                        let _ = write!(text, "{} subquer(ies)", subqueries.len());
                    }
                }
            }
            text.push(']');
            text
        }
        ColumnTest::Array(access) => match access {
            ArrayAccess::Walk(tokens) => format!("array walk {}", tokens_text(tokens)),
            ArrayAccess::BelowWildcard(tokens) => {
                format!("array below-wildcard {}", tokens_text(tokens))
            }
            ArrayAccess::AnyLeaf => "array any-leaf".to_owned(),
        },
        ColumnTest::LogEventRanges(ranges) => format!(
            "log-event ranges ({} true, {} false)",
            ranges.true_ranges.len(),
            ranges.false_ranges.len()
        ),
    }
}

/// # Returns
///
/// The text of an array suffix.
fn tokens_text(tokens: &[PathToken]) -> String {
    if tokens.is_empty() {
        return "[]".to_owned();
    }
    column_text(&ColumnPattern {
        namespace: Namespace::Default,
        tokens: tokens.into(),
    })
}
