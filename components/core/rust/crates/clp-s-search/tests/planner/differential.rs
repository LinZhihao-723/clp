//! The planner against the reference evaluator over every fixture archive.
//!
//! For every readable fixture archive and every query of the suite (plus planner-specific extra
//! queries), each stored record is evaluated by the reference evaluator (`Query::evaluate` over
//! the record's stored values). The plan must:
//!
//! * keep every table holding a matching record as a candidate (pruning is sound);
//! * mark a table match-all only if every record of it matches;
//! * give every other candidate a residual filter that, evaluated by the binding contract, selects
//!   exactly the matching records (bindings and dictionary prefilters are exact).

