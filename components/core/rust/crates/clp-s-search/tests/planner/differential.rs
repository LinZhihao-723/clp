/// Counts over the whole differential.
#[derive(Default)]
struct Tally {
    plans: u64,
    pruned: u64,
    match_all_tables: u64,
    residual_tables: u64,
    rows_checked: u64,
    unverifiable_rows: u64,
    matching_rows: u64,
    dictionary_requests: u64,
    templates: u64,
    skipped_queries: u64,
    archives_with_auto_generated_keys: u64,
}

/// # Returns
///
/// The suite queries plus the extra queries, case-sensitive, and the extra text queries again
/// case-insensitive.
///
/// # Errors
///
/// Returns an error if:
///
/// * Forwards [`suite_queries`]'s return values on failure.
pub fn all_queries() -> anyhow::Result<Vec<SuiteQuery>> {
    let extra = |id: String, kql: &str, is_case_sensitive: bool| SuiteQuery {
        id,
        target: String::new(),
        expected_rust_count: None,
        kql: kql.to_owned(),
        is_case_sensitive,
        tge: None,
        tle: None,
        projection: Vec::new(),
    };
    let mut queries = suite_queries()?;
    queries.extend(
        EXTRA_QUERIES
            .iter()
            .enumerate()
            .map(|(index, kql)| extra(format!("extra-{index}"), kql, true)),
    );
    queries.extend(
        EXTRA_QUERIES
            .iter()
            .filter(|kql| kql.contains('"'))
            .enumerate()
            .map(|(index, kql)| extra(format!("extra-ignore-case-{index}"), kql, false)),
    );
    Ok(queries)
}

/// # Returns
///
/// The query and projection of `suite_query`, or `None` if it does not parse or reaches `@` keys
/// of an archive that has them (record views walk only the default namespace, so the reference
/// cannot see those keys).
pub fn prepare(
    suite_query: &SuiteQuery,
    has_auto_generated_keys: bool,
) -> Option<(Arc<Query>, RecordProjection)> {
    let options = QueryOptions::default().with_case_sensitivity(suite_query.is_case_sensitive);
    let query = Query::from_kql(&suite_query.kql, &options).ok()?;
    let reaches_auto_generated_keys = query.leaves().iter().any(|leaf| match &leaf.column {
        ColumnRef::AnyLeaf => true,
        ColumnRef::Path(pattern) => Namespace::AutoGenerated == pattern.namespace,
        _ => false,
    });
    if has_auto_generated_keys && reaches_auto_generated_keys {
        return None;
    }
    let query = Arc::new(query.with_time_bounds(TimeBounds::from_epoch_millis(
        suite_query.tge,
        suite_query.tle,
    )));
    let projection = if suite_query.projection.is_empty() {
        RecordProjection::Full
    } else {
        RecordProjection::Columns(
            suite_query
                .projection
                .iter()
                .filter_map(|column| ColumnPattern::parse(column).ok())
                .collect(),
        )
    };
    Some((query, projection))
}

#[test]
fn plans_agree_with_the_reference_evaluator_on_every_fixture() -> anyhow::Result<()> {
    let queries = all_queries()?;
    let mut stats = Tally::default();
    let mut failures = Vec::new();
    for path in readable_archives() {
        let name = stem(&path);
        let rows = ArchiveRows::load(&path)?;
        let archive = OpenedArchive::open(&path)?;
        let tree = archive.storage.index().schema_tree();
        let has_auto_generated_keys = tree
            .subtree_root(b"@", NodeType::Object)
            .is_some_and(|root| !tree.children(root).is_empty());
        stats.archives_with_auto_generated_keys += u64::from(has_auto_generated_keys);
        for suite_query in &queries {
            let Some((query, projection)) = prepare(suite_query, has_auto_generated_keys) else {
                stats.skipped_queries += 1;
                continue;
            };
            let (planned, num_requests) = match plan(&archive, &query, &projection) {
                Ok(result) => result,
                Err(error) => {
                    failures.push(format!(
                        "{name} / {}: planning failed: {error:#}",
                        suite_query.id
                    ));
                    continue;
                }
            };
            stats.plans += 1;
            stats.dictionary_requests += num_requests as u64;
            check_plan(&rows, &query, &planned, &mut stats, &mut |message| {
                failures.push(format!(
                    "{name} / {} `{}`: {message}",
                    suite_query.id, suite_query.kql
                ));
            });
        }
    }

    println!(
        "{} plans ({} pruned, {} templates), {} match-all and {} residual tables, {} rows checked \
         ({} matching, {} unverifiable), {} dictionary requests, {} queries skipped ({} archives \
         with `@` keys)",
        stats.plans,
        stats.pruned,
        stats.templates,
        stats.match_all_tables,
        stats.residual_tables,
        stats.rows_checked,
        stats.matching_rows,
        stats.unverifiable_rows,
        stats.dictionary_requests,
        stats.skipped_queries,
        stats.archives_with_auto_generated_keys
    );
    assert!(
        stats.rows_checked > 100_000,
        "the differential covers enough rows"
    );
    assert!(
        stats.residual_tables > 1_000,
        "residual filters are exercised"
    );
    assert!(
        stats.dictionary_requests > 0,
        "the dictionary protocol is exercised"
    );
    if !failures.is_empty() {
        let mut report = format!("{} disagreements; the first ones:\n", failures.len());
        for failure in failures.iter().take(40) {
            let _ = writeln!(report, "  {failure}");
        }
        panic!("{report}");
    }
    Ok(())
}

/// Checks one planning outcome against the reference over every row of the archive.
///
/// # Type Parameters
///
/// * `FailType` - Receives each disagreement.
fn check_plan<FailType: FnMut(String)>(
    rows: &ArchiveRows,
    query: &Query,
    planned: &Planned,
    stats: &mut Tally,
    fail: &mut FailType,
) {
    let plan = match planned {
        Planned::Pruned(report) => {
            stats.pruned += 1;
            for (table, table_rows) in rows.tables.iter().enumerate() {
                for row in table_rows {
                    if row.unverifiable.is_some() {
                        continue;
                    }
                    stats.rows_checked += 1;
                    if rows.reference_matches(query, row) {
                        fail(format!(
                            "pruned ({report:?}) but table {table} has the matching record {}",
                            row.record
                        ));
                        return;
                    }
                }
            }
            return;
        }
        Planned::Plan(plan) => plan,
    };
    stats.templates += plan.templates().len() as u64;
    let mut candidates = plan.tables().iter().peekable();
    for (table, table_rows) in rows.tables.iter().enumerate() {
        let table_plan = candidates.next_if(|candidate| candidate.table.get() as usize == table);
        match table_plan.map(|candidate| &candidate.filter) {
            Some(TableFilterPlan::MatchAll) => stats.match_all_tables += 1,
            Some(TableFilterPlan::Residual(_)) => stats.residual_tables += 1,
            None => {}
        }
        for row in table_rows {
            if row.unverifiable.is_some() {
                stats.unverifiable_rows += 1;
                continue;
            }
            stats.rows_checked += 1;
            let is_reference_match = rows.reference_matches(query, row);
            stats.matching_rows += u64::from(is_reference_match);
            let is_plan_match = match table_plan.map(|candidate| &candidate.filter) {
                None => false,
                Some(TableFilterPlan::MatchAll) => true,
                Some(TableFilterPlan::Residual(residual)) => {
                    let mut evaluator = ResidualEvaluator {
                        query,
                        residual,
                        prefilter_violations: Vec::new(),
                    };
                    let is_match = evaluator.matches(row);
                    for violation in evaluator.prefilter_violations {
                        fail(format!("table {table}: {violation}"));
                    }
                    is_match
                }
            };
            if is_plan_match != is_reference_match {
                fail(format!(
                    "table {table}: the plan says {is_plan_match}, the reference \
                     {is_reference_match}, on {}\n{plan}",
                    row.record
                ));
                return;
            }
        }
    }
}
