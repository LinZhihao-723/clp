//! Column references of predicates.

use crate::QueryError;
use crate::kql::unescape_kql;

/// What a predicate reads.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum ColumnRef {
    /// A record path such as `a.b` or `a.*.c`, resolved against each archive's schema tree.
    Path(ColumnPattern),

    /// Every non-metadata leaf, in every namespace (KQL bare values).
    AnyLeaf,

    /// The archive's authoritative timestamp column, bound by node id (time bounds).
    AuthoritativeTimestamp,

    /// A field of the range index (`$` namespace), constant over `log_event_idx` ranges. The
    /// pattern's namespace is [`Namespace::RangeIndex`].
    RangeIndexField(ColumnPattern),
}

impl ColumnRef {
    /// Factory function.
    ///
    /// # Returns
    ///
    /// The reference a KQL column denotes: [`Self::AnyLeaf`] for the pure wildcard `*` in the
    /// default namespace, [`Self::RangeIndexField`] for the `$` namespace, and [`Self::Path`]
    /// otherwise.
    #[must_use]
    pub fn from_pattern(pattern: ColumnPattern) -> Self {
        match pattern.namespace {
            Namespace::Default if [PathToken::AnyDepth] == *pattern.tokens => Self::AnyLeaf,
            Namespace::RangeIndex => Self::RangeIndexField(pattern),
            _ => Self::Path(pattern),
        }
    }
}

/// A namespaced KQL column path.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct ColumnPattern {
    pub namespace: Namespace,
    pub tokens: Box<[PathToken]>,
}

impl ColumnPattern {
    /// Factory function.
    ///
    /// Parses a column with the KQL column grammar (used for projections).
    ///
    /// # Returns
    ///
    /// The pattern on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`QueryError::InvalidColumn`] if `text` is not a valid KQL column.
    /// * [`QueryError::InvalidEscape`] if `text` contains an invalid escape sequence.
    pub fn parse(text: &str) -> Result<Self, QueryError> {
        Self::tokenize(text.as_bytes(), 0)
    }

    /// # Returns
    ///
    /// Whether the path has no wildcard token (required for projections).
    #[must_use]
    pub fn is_literal(&self) -> bool {
        !self.tokens.contains(&PathToken::AnyDepth)
    }

    /// Splits a raw KQL column into its namespace and tokens (C++ `tokenize_column_descriptor`
    /// followed by `ColumnDescriptor::create_from_escaped_tokens`).
    ///
    /// The first byte selects the namespace if it is one of `@`, `$`, `!` or `#`. Unescaped dots
    /// separate tokens, no token may be empty, a token that is exactly an unescaped `*` is a
    /// wildcard, and consecutive wildcards collapse into one.
    ///
    /// # Returns
    ///
    /// The pattern on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`QueryError::InvalidColumn`] if a token is empty or the text ends inside an escape.
    /// * [`QueryError::InvalidEscape`] if a token contains an invalid escape sequence.
    pub(crate) fn tokenize(text: &[u8], base_position: usize) -> Result<Self, QueryError> {
        let invalid_column = || QueryError::InvalidColumn {
            text: String::from_utf8_lossy(text).into(),
        };

        let namespace = match text.first() {
            Some(b'@') => Namespace::AutoGenerated,
            Some(b'$') => Namespace::RangeIndex,
            Some(&sigil @ (b'!' | b'#')) => Namespace::Reserved(sigil),
            _ => Namespace::Default,
        };
        let start = usize::from(Namespace::Default != namespace);

        let mut tokens: Vec<PathToken> = Vec::new();
        let mut current = RawToken::default();
        let mut is_escaped = false;
        for (index, &byte) in text.iter().enumerate().skip(start) {
            let position = base_position + index;
            if is_escaped {
                is_escaped = false;
                if b'.' != byte {
                    current.push(b'\\', position - 1);
                }
                current.push(byte, position);
                continue;
            }
            match byte {
                b'\\' => is_escaped = true,
                b'.' => {
                    if current.bytes.is_empty() {
                        return Err(invalid_column());
                    }
                    current.unescape_into(&mut tokens)?;
                    current = RawToken::default();
                }
                _ => current.push(byte, position),
            }
        }
        if is_escaped || current.bytes.is_empty() {
            return Err(invalid_column());
        }
        current.unescape_into(&mut tokens)?;

        Ok(Self {
            namespace,
            tokens: tokens.into_boxed_slice(),
        })
    }

    /// Prepends `prefix` to this pattern, as a nested query `prefix: {...}` does, collapsing the
    /// wildcards that meet at the seam.
    ///
    /// # Returns
    ///
    /// The prefixed pattern, in the prefix's namespace, on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`QueryError::NamespaceInNestedQuery`] if this pattern declares a namespace.
    pub(crate) fn prepend(&self, prefix: &Self) -> Result<Self, QueryError> {
        if Namespace::Default != self.namespace {
            return Err(QueryError::NamespaceInNestedQuery);
        }
        let mut tokens: Vec<PathToken> =
            Vec::with_capacity(prefix.tokens.len() + self.tokens.len());
        for token in prefix.tokens.iter().chain(self.tokens.iter()) {
            if PathToken::AnyDepth == *token && tokens.last() == Some(&PathToken::AnyDepth) {
                continue;
            }
            tokens.push(token.clone());
        }
        Ok(Self {
            namespace: prefix.namespace,
            tokens: tokens.into_boxed_slice(),
        })
    }
}

/// One token of a column path.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum PathToken {
    /// A literal key (unescaped).
    Key(Box<[u8]>),

    /// `*`: zero or more levels.
    AnyDepth,
}

/// The namespace a column path lives in.
#[non_exhaustive]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Namespace {
    /// The record's own keys.
    Default,

    /// Auto-generated keys (`@`).
    AutoGenerated,

    /// Range-index fields (`$`).
    RangeIndex,

    /// A reserved namespace, identified by its sigil (`!` or `#`); no archive writes keys into it.
    Reserved(u8),
}

/// The raw bytes of one column token, with the query position of each byte.
#[derive(Default)]
struct RawToken {
    bytes: Vec<u8>,
    positions: Vec<usize>,
}

impl RawToken {
    /// Appends `byte`, found at `position` in the query.
    fn push(&mut self, byte: u8, position: usize) {
        self.bytes.push(byte);
        self.positions.push(position);
    }

    /// Unescapes the token and appends it to `tokens`, collapsing consecutive wildcards.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`QueryError::InvalidEscape`] if the token contains an invalid escape sequence.
    fn unescape_into(&self, tokens: &mut Vec<PathToken>) -> Result<(), QueryError> {
        let escaped =
            unescape_kql(&self.bytes, false).map_err(|offset| QueryError::InvalidEscape {
                position: self.positions.get(offset).copied().unwrap_or_default(),
            })?;
        let token = if b"*" == escaped.as_slice() {
            PathToken::AnyDepth
        } else {
            let mut key = Vec::with_capacity(escaped.len());
            let mut is_escaped = false;
            for &byte in &escaped {
                if !is_escaped && b'\\' == byte {
                    is_escaped = true;
                    continue;
                }
                is_escaped = false;
                key.push(byte);
            }
            PathToken::Key(key.into_boxed_slice())
        };
        if PathToken::AnyDepth == token && tokens.last() == Some(&PathToken::AnyDepth) {
            return Ok(());
        }
        tokens.push(token);
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::ColumnPattern;
    use super::ColumnRef;
    use super::Namespace;
    use super::PathToken;
    use crate::QueryError;

    /// # Returns
    ///
    /// A key path token named `text`.
    fn key(text: &str) -> PathToken {
        PathToken::Key(text.as_bytes().into())
    }

    /// # Returns
    ///
    /// The column pattern that `text` spells.
    ///
    /// # Panics
    ///
    /// Panics if `text` isn't a valid column pattern.
    fn parse(text: &str) -> ColumnPattern {
        ColumnPattern::parse(text).expect("column should parse")
    }

    #[test]
    fn dots_split_tokens_and_escaped_dots_do_not() {
        assert_eq!(*parse("a.b.c").tokens, [key("a"), key("b"), key("c")]);
        assert_eq!(*parse(r"a\.b.c").tokens, [key("a.b"), key("c")]);
        assert_eq!(parse("a").namespace, Namespace::Default);
    }

    #[test]
    fn namespaces_come_from_the_first_unescaped_byte() {
        for (text, namespace) in [
            ("@column", Namespace::AutoGenerated),
            ("$column", Namespace::RangeIndex),
            ("!column", Namespace::Reserved(b'!')),
            ("#column", Namespace::Reserved(b'#')),
        ] {
            let pattern = parse(text);
            assert_eq!(pattern.namespace, namespace, "{text}");
            assert_eq!(*pattern.tokens, [key("column")], "{text}");
        }
        for sigil in ["@", "$", "!", "#"] {
            let pattern = parse(&format!(r"\{sigil}column"));
            assert_eq!(pattern.namespace, Namespace::Default);
            assert_eq!(*pattern.tokens, [key(&format!("{sigil}column"))]);
        }
    }

    #[test]
    fn empty_tokens_are_invalid() {
        for text in [".a", "a.", "a..c", "a.b.", "", "@", "a\\"] {
            assert!(
                matches!(
                    ColumnPattern::parse(text),
                    Err(QueryError::InvalidColumn { .. })
                ),
                "{text:?} should be an invalid column"
            );
        }
    }

    #[test]
    fn wildcards_are_whole_tokens_and_collapse() {
        assert_eq!(
            *parse("a.*.b").tokens,
            [key("a"), PathToken::AnyDepth, key("b")]
        );
        assert_eq!(*parse("*.*.b").tokens, [PathToken::AnyDepth, key("b")]);
        assert_eq!(*parse(r"a.\*").tokens, [key("a"), key("*")]);
        assert_eq!(*parse("a*b").tokens, [key("a*b")]);
        assert_eq!(*parse("a?").tokens, [key("a?")]);
        assert!(parse("a.b").is_literal());
        assert!(!parse("a.*").is_literal());
    }

    #[test]
    fn escapes_in_keys_follow_the_kql_rules() {
        assert_eq!(*parse(r"a\\b").tokens, [key(r"a\b")]);
        assert_eq!(*parse(r"a\u0041").tokens, [key("aA")]);
        assert_eq!(*parse(r"a\u002e").tokens, [key("a.")]);
        assert_eq!(*parse(r"\u002A").tokens, [key("*")]);
        assert_eq!(*parse(r"a\?").tokens, [key("a?")]);
        assert_eq!(*parse(r"a\tb").tokens, [key("a\tb")]);
        assert!(matches!(
            ColumnPattern::parse(r"a\:b"),
            Err(QueryError::InvalidEscape { position: 1 })
        ));
        assert!(matches!(
            ColumnPattern::parse(r"x.a\zb"),
            Err(QueryError::InvalidEscape { position: 3 })
        ));
    }

    #[test]
    fn prepend_applies_the_prefix_namespace_and_collapses_wildcards() -> anyhow::Result<()> {
        let prefixed = parse("b").prepend(&parse("@a.*"))?;
        assert_eq!(prefixed.namespace, Namespace::AutoGenerated);
        assert_eq!(*prefixed.tokens, [key("a"), PathToken::AnyDepth, key("b")]);
        let collapsed = parse("*").prepend(&parse("*"))?;
        assert_eq!(*collapsed.tokens, [PathToken::AnyDepth]);
        assert!(matches!(
            parse("@b").prepend(&parse("a")),
            Err(QueryError::NamespaceInNestedQuery)
        ));
        Ok(())
    }

    #[test]
    fn column_references_classify_patterns() {
        assert_eq!(ColumnRef::from_pattern(parse("*")), ColumnRef::AnyLeaf);
        assert_eq!(ColumnRef::from_pattern(parse("*.*")), ColumnRef::AnyLeaf);
        assert!(matches!(
            ColumnRef::from_pattern(parse("@*")),
            ColumnRef::Path(_)
        ));
        assert!(matches!(
            ColumnRef::from_pattern(parse("$_filename")),
            ColumnRef::RangeIndexField(_)
        ));
        assert!(matches!(
            ColumnRef::from_pattern(parse("a.*")),
            ColumnRef::Path(_)
        ));
    }
}
